'use strict';
const assert=require('assert/strict');
module.exports=async function run({win,js,waitFor,book}){
  await book('Genesis');await waitFor("document.querySelector('#rOut .cell[data-k=he] .w')",'Hebräischer Lesetext für Anzeigeoptionen');
  const word=await js("document.querySelector('#rOut .cell[data-k=he] .w').textContent");
  assert(/[\u05B0-\u05BC]/.test(word),'Vokalisierter Testtext');
  await js("document.querySelector('#dispBtn').click()");
  const set=async(id,value)=>js(`{const c=document.getElementById(${JSON.stringify(id)});${typeof value==='boolean'?'c.checked':'c.value'}=${JSON.stringify(value)};c.dispatchEvent(new Event('input',{bubbles:true}));}`);
  await set('dHe','1.6');await set('dGr','1.4');await set('dDe','1.2');await set('dHov','1.4');
  assert.equal(await js("document.querySelector('#rOut').style.getPropertyValue('--hef')"),'1.6');
  assert.equal(await js("document.querySelector('#rOut').style.getPropertyValue('--grf')"),'1.4');
  assert.equal(await js("document.querySelector('#rOut').style.getPropertyValue('--def')"),'1.2');
  assert.equal(await js("document.documentElement.style.getPropertyValue('--hovf')"),'1.4');
  assert.equal(await js("document.querySelector('#dHeV').textContent"),'160 %');
  await set('dNiq',true);await set('dCan',true);
  await waitFor("document.querySelector('#rOut .cell[data-k=he] .w')?.textContent==='בראשית'",'Vokal-/Betonungszeichen ausgeblendet');
  await set('dMar','narrow');await set('dHdSt',true);await set('dHideTabs',false);await set('dShr',false);await set('dPvDe','*');
  assert(await js("document.body.classList.contains('mar-narrow') && document.body.classList.contains('head-stick') && !document.body.classList.contains('dock-shrink')"));
  await js("document.querySelector('#dispClose').click()");
  const loaded=new Promise(resolve=>win.webContents.once('did-finish-load',resolve));
  win.reload();await loaded;
  await waitFor("[...document.querySelectorAll('#tree .lib-item')].some(n=>n.dataset.key.endsWith('¦Genesis'))",'Bibliothek nach Neuladen');
  await book('Genesis');
  await waitFor("document.querySelector('#rOut .cell[data-k=he] .w')?.textContent==='בראשית' && document.querySelector('#dNiq').checked && document.querySelector('#dCan').checked",'Anzeigeeinstellungen nach Neustart');
  await js("document.querySelector('#dispBtn').click()");
  assert.equal(await js("document.querySelector('#dPvDe').value"),'*');
  assert.equal(await js("document.querySelector('#dHe').value"),'1.6');
  assert.equal(await js("document.querySelector('#dHideTabs').checked"),false);
  assert(await js("document.body.classList.contains('mar-narrow') && document.body.classList.contains('head-stick') && !document.body.classList.contains('dock-shrink')"));
  await set('dNiq',false);await set('dCan',false);
  await waitFor(`document.querySelector('#rOut .cell[data-k=he] .w')?.textContent===${JSON.stringify(word)}`,'Vollständige Vokalisierung wiederhergestellt');
  await js("document.querySelector('#dispPanel').dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}))");
  assert.equal(await js("document.querySelector('#dispPanel').hidden"),true);
  console.log('Electron: Schriftgrößen, Vokal-/Betonungszeichen, Leseoptionen und gespeicherte Anzeige nach Neustart bestanden.');
};
