'use strict';
const assert = require('node:assert/strict');
const {ipcMain} = require('electron');
const fs = require('node:fs');
const path = require('node:path');
module.exports = function setup({profile, handlers}) {
  const file = path.join(profile, 'fixture-notes.json');
  let active = false;
  const list = () => fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : [];
  const save = items => {fs.writeFileSync(file, JSON.stringify(items)); return items;};
  handlers['notes:list'] = list;
  handlers['notes:save'] = (_event, item) => save([...list().filter(n => n.id !== item.id), {...item, ts: item.ts || Date.now()}]);
  handlers['notes:delete'] = (_event, id) => save(list().filter(n => n.id !== id));
  const oldOutline = handlers['outline:get'], oldTopics = handlers['topics:status'], oldSection = handlers['links:section'];
  handlers['outline:get'] = (_event, book) => active && book === 'Genesis' ? require('../../outlines/Genesis.json') : oldOutline();
  handlers['topics:status'] = () => active ? {complete: true, count: 1, total: 1} : oldTopics();
  handlers['topics:section'] = () => active ? [{slug: 'creation', en: 'Creation', he: 'בריאה', verses: [1]}] : [];
  handlers['topics:list'] = () => [{s: 'creation', en: 'Creation', he: 'בריאה', n: 1}];
  handlers['topics:get'] = () => ({slug: 'creation', en: 'Creation', he: 'בריאה', notable: [], sources: [], links: [], description: {en: 'A local test topic.'}});
  handlers['links:section'] = (...args) => active ? [{v1: 1, v2: 1, other: 'Exodus 1:1', type: 'parallel', cat: 'Tanakh'}] : oldSection(...args);
  return async function run({win, js, waitFor, book}) {
    active = true;
    // The earlier commentary flow installs its own section provider.
    ipcMain.removeHandler('links:section');
    ipcMain.handle('links:section', handlers['links:section']);
    const loaded = new Promise(resolve => win.webContents.once('did-finish-load', resolve));
    win.reload(); await loaded;
    await waitFor("document.querySelectorAll('#tree .lib-item').length >= 3", 'Bibliothek für ergänzende Leserprüfungen');
    await book('Genesis');
    await waitFor("document.querySelector('#rOut .row[data-l=\"1\"] .bm')", 'Lesezeichen am Vers');
    await js("document.querySelector('#rOut .row[data-l=\"1\"] .bm').click()");
    await waitFor("document.querySelector('#noteDlg[open]')", 'Versnotiz öffnen');
    await js("document.querySelector('#ndText').value='Prüfnotiz **Anfang**';document.querySelector('#ndTags').value='Test, Genesis';document.querySelector('#ndSave').click()");
    await waitFor("document.querySelector('#rOut .row[data-l=\"1\"] .rnote')?.textContent==='Prüfnotiz **Anfang**'", 'Versnotiz gespeichert');
    assert.equal(list().length, 1);
    await js("document.querySelector('nav [data-tab=notes]').click()");
    await waitFor("document.querySelector('#nOut .nitem .nt b')?.textContent==='Anfang'", 'Notizformatierung im Notizenreiter');
    await js("document.querySelector('#nFilter').value='kein Treffer';document.querySelector('#nFilter').dispatchEvent(new Event('input',{bubbles:true}))");
    await waitFor("!document.querySelector('#nOut .nitem')", 'Notizenfilter');
    await js("document.querySelector('#nFilter').value='';document.querySelector('#nFilter').dispatchEvent(new Event('input',{bubbles:true}))");
    await waitFor("document.querySelector('#nOut [data-del]')", 'Notiz nach Filter zurück');
    await js("document.querySelector('#nOut [data-del]').click()");
    await waitFor("!document.querySelector('#nOut .nitem') && document.querySelector('#undoBar.on button')", 'Notiz gelöscht');
    await js("document.querySelector('#undoBar button').click()");
    await waitFor("document.querySelector('#nOut .nitem')", 'Notiz wiederhergestellt');
    assert.equal(list().length, 1);
    await js("document.querySelector('nav [data-tab=read]').click();document.querySelector('#olBtn').click()");
    await waitFor("!document.querySelector('#outlinePanel').hidden && document.querySelector('#olBody .olp')", 'Echte Genesis-Gliederung');
    assert(await js("document.querySelector('#olBody').textContent.includes('Weltschöpfung')"));
    await js("document.querySelector('#olBody .olp').click()");
    await waitFor("document.querySelector('#rOut .row[data-l=\"1\"]')", 'Navigation aus der Gliederung');
    await js("document.querySelector('#olClose').click()");
    await waitFor("!document.querySelector('#lkBtn').hidden", 'Lokale Verknüpfung');
    await js("document.querySelector('#lkFilter').value='';document.querySelector('#lkBtn').click()");
    await waitFor("document.querySelector('#lkBody a[data-ref=\"Exodus 1:1\"]')", 'Verknüpfung gerendert');
    await js("document.querySelector('#lkBody a[data-ref=\"Exodus 1:1\"]').click()");
    await waitFor("document.querySelector('#rTitle').textContent.includes('Exodus')", 'Sprung aus Verknüpfung');
    await book('Genesis');
    await waitFor("!document.querySelector('#tpBtn').hidden", 'Themen verfügbar');
    await js("document.querySelector('#tpBtn').click()");
    await waitFor("document.querySelector('#tpBody [data-slug=creation]')", 'Themen zum Abschnitt');
    await js("document.querySelector('#tpBody [data-slug=creation]').click()");
    await waitFor("document.querySelector('#tpTitle').textContent==='Creation'", 'Themenkarte');
    await js("document.querySelector('#tpClose').click();document.querySelector('#mapBtn').click()");
    await waitFor("!document.querySelector('#mapPanel').hidden && document.querySelector('#mapCv').width > 0", 'Karte im echten Fenster');
    // mapOpen populates the list in requestAnimationFrame. Canvas has a
    // non-zero default width before that frame, especially under Linux/Xvfb.
    await waitFor("document.querySelector('#mapInfo .sub')?.textContent.trim().length > 0", 'Karteninformation nach dem ersten Kartendurchlauf');
    await js("document.querySelector('#mapClose').click()");
    // A full reload checks persisted notes and the reader's live module adapters.
    const restored = new Promise(resolve => win.webContents.once('did-finish-load', resolve));
    win.reload(); await restored;
    await waitFor("document.querySelector('#rOut .rnote')?.textContent==='Prüfnotiz **Anfang**'", 'Notiz nach Neustart');
    assert.equal(list().length, 1);
    console.log('Electron: Notiz speichern/filtern/löschen/rückgängig, echte Gliederung, Verknüpfungssprung, Themen, Karte und gespeicherte Notiz nach Neustart bestanden.');
  };
};
