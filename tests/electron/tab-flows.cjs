'use strict';
const assert = require('assert/strict');
module.exports = async function run({win, js, waitFor, book}) {
  await book('Genesis');
  await waitFor("document.querySelector('#rTitle').textContent.includes('Genesis') && document.querySelector('#rOut .row')", 'Genesis vor Tabwechsel');
  const count = await js("document.querySelectorAll('#tabbar .tab').length");
  await js("document.querySelector('#tabNew').click()");
  assert.equal(await js("document.querySelectorAll('#tabbar .tab').length"), count + 1);
  await book('Exodus');
  await waitFor("document.querySelector('#rTitle').textContent.includes('Exodus') && document.querySelector('#rOut .row')", 'Exodus im neuen Tab');
  await js("document.querySelector('#nextSec').click()");
  await waitFor("document.querySelector('#tabbar .tab.active').title.includes('2')", 'Zweites Kapitel im Tab');
  const title = await js("document.querySelector('#tabbar .tab.active').title");
  await js("document.querySelector('#tabbar .tab.active button').click()");
  await waitFor("document.querySelector('#rTitle').textContent.includes('Genesis')", 'Benachbarter Tab nach Schließen');
  await js("window.__reopenTab()");
  await waitFor(`document.querySelector('#tabbar .tab.active')?.title === ${JSON.stringify(title)} && document.querySelector('#rOut .row')`, 'Geschlossener Tab am gemerkten Kapitel');
  assert.equal(await js("document.querySelectorAll('#tabbar .tab').length"), count + 1);
  await book('Genesis');
  await waitFor("document.querySelector('#rTitle').textContent.includes('Genesis') && !document.querySelector('#navBack').disabled", 'Buchwechsel mit Verlauf');
  await js("document.querySelector('#navBack').click()");
  await waitFor(`document.querySelector('#tabbar .tab.active')?.title === ${JSON.stringify(title)} && document.querySelector('#rOut .row')`, 'Zurück zu Exodus Kapitel 2');
  await waitFor("document.querySelector('#pane2')?.contentDocument?.querySelector('#tabbar .tab.active')", 'Eigene Tabs im zweiten Fenster');
  const paneTitle = await js("document.querySelector('#pane2').contentDocument.querySelector('#tabbar .tab.active').title");
  const loaded = new Promise(resolve => win.webContents.once('did-finish-load', resolve));
  win.reload(); await loaded;
  await waitFor(`document.querySelector('#tabbar .tab.active')?.title === ${JSON.stringify(title)} && document.querySelector('#rOut .row')`, 'Tabs und Kapitel nach Neustart');
  assert.equal(await js("document.querySelectorAll('#tabbar .tab').length"), count + 1);
  await waitFor(`document.querySelector('#pane2')?.contentDocument?.querySelector('#tabbar .tab.active')?.title === ${JSON.stringify(paneTitle)}`, 'Unabhängige Sitzung des zweiten Fensters nach Neustart');
  assert(await js("JSON.parse(localStorage.getItem('session')).tabs.some(t => t.key?.endsWith('¦Exodus'))"));
  console.log('Electron: Neue Tabs, Schließen/Wiederöffnen, Buchverlauf und Sitzungswiederherstellung bestanden.');
};
