"""Build the first text-critical witness adapter (Tal–Florentin), offline.
Verse correspondence is based on exact consonantal word anchors, not inferred
Hebrew readings. Keep source numbering, uncertainty and transpositions explicit.
"""
import collections, difflib, hashlib, html, json, re
FINAL=str.maketrans('ךםןףץ','כמנפצ')
def cons(s):return ''.join(re.findall('[א-ת]',html.unescape(re.sub('<[^>]*>','',s)))).translate(FINAL)
def build(root,verses):
    manifest=json.loads((root/'bundled/manifest.json').read_text())['items']
    mt={};index=collections.defaultdict(list);locks={};unknown=[]
    for book in ['Genesis','Exodus','Leviticus','Numbers','Deuteronomy']:
        item=next(i for i in manifest if i['title']==book and i['versionTitle'].startswith('Westminster'))
        raw=(root/'bundled'/item['rel']).read_bytes();locks[book]=hashlib.sha256(raw).hexdigest()
        doc=json.loads(raw)
        for c,chapter in enumerate(doc['text'],1):
            A=[];ar=[];B=[];br=[];mt_words={}
            for v,verse in enumerate(chapter,1):
                ref=f'{book} {c}:{v}'
                mt[ref]=html.unescape(re.sub('<[^>]*>','',verse))
                mt_words[ref]=[]
                for word in re.findall(r'<span class="w"[^>]*>(.*?)</span>',verse):
                    if cons(word):A.append(cons(word));ar.append(ref);mt_words[ref].append(cons(word))
            refs=[r for r in verses if r.startswith(f'{book} {c}:')]
            for ref in refs:
                for word,mask,wid in verses[ref]['words']:B.append(cons(word));br.append(ref)
            # Exact complete verses at the same source coordinate are hard
            # anchors. They prevent repeated offering formulas (Numbers 7)
            # from drifting to another day's otherwise identical wording.
            anchors={r for r in refs if [cons(w) for w,mask,wid in verses[r]['words']]==mt_words.get(r)}
            def anchored(words,refs):
                out=[];labels=[];last=None
                for word,ref in zip(words,refs):
                    if ref!=last and ref in anchors:out.append('#'+ref);labels.append(ref)
                    out.append(word);labels.append(ref);last=ref
                return out,labels
            A,ar=anchored(A,ar);B,br=anchored(B,br)
            hits=collections.defaultdict(collections.Counter)
            for a,b,size in difflib.SequenceMatcher(None,A,B,autojunk=False).get_matching_blocks():
                for i in range(size):
                    if not A[a+i].startswith('#'):hits[br[b+i]][ar[a+i]]+=1
            for ref in refs:
                n=len(verses[ref]['words']);counts=hits[ref];total=sum(counts.values())
                # Do not manufacture correspondence for displaced additions or
                # poorly anchored passages. Unresolved verses remain inspectable
                # under their own Tal reference.
                candidates=[r for r,count in counts.items() if count>=min(3,n) and count/n>=.12]
                own=[cons(w) for w,mask,wid in verses[ref]['words']]
                if own and own==mt_words.get(ref):candidates=[ref];total=n
                resolved=bool(candidates) and total/max(n,1)>=.55
                verses[ref]['mtRefs']=candidates if resolved else []
                verses[ref]['mapping']='word-anchors' if resolved else 'unresolved'
                if not resolved:unknown.append(ref)
                for r in verses[ref]['mtRefs']:index[r].append(ref)
    out={'schema':1,'base':{'id':'MT','title':'Westminster Leningrad Codex (OSHB)','sha256':locks},
         'witnesses':{'SMR':{'title':'Samaritanus · Tal–Florentin','doi':'10.11647/OBP.0415','license':'CC BY-NC 4.0'}},
         'verses':verses,'mt':mt,'mtIndex':dict(index),'unresolved':unknown}
    payload=json.dumps(out,ensure_ascii=False,separators=(',',':'))
    (root/'textcrit-data.js').write_text('// Generated by tools/samaritan/build.py; Tal–Florentin CC BY-NC 4.0; OSHB source attribution in licenses.\n(function(d){if(typeof module!=="undefined"&&module.exports)module.exports=d;else window.TEXTCRIT_DATA=d;})('+payload+');\n')
    print('Textcrit:',len(verses),'Tal verses;',len(unknown),'without confident MT anchors;',len(payload.encode()),'bytes')
