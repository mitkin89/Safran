'use strict';
const assert = require('assert');
const S = require('./search'), R = require('./reader');
const mk = o => S.makeMatcher(o);
const t = R.normalize('Am Anfang schuf Gott Himmel und Erde.');
assert(mk({ terms: ['anf*', 'gott', 'erd*'], distance: 10, ordered: true })(t));
assert(!mk({ terms: ['erd*', 'gott', 'anf*'], distance: 10, ordered: true })(t));
assert(mk({ terms: ['erd*', 'gott', 'anf*'], distance: 10 })(t));
assert(!mk({ terms: ['anf*', 'erd*'], distance: 3 })(t));
assert(mk({ terms: ['anf*', 'erd*'], distance: 4 })(t));
assert(mk({ terms: ['anf*', 'erd*'], distance: -1 })(t));
assert(!mk({ terms: ['gott'] })(R.normalize('Gottes Wort')));
assert(mk({ terms: ['gott*'] })(R.normalize('Gottes Wort')));
assert(mk({ terms: ['raschi'], fuzzy: true })(R.normalize('Rashi sagt')));
assert(mk({ terms: ['avraham'], fuzzy: true })(R.normalize('Abraham ging')));
assert(mk({ terms: ['semuel'], fuzzy: true })(R.normalize('Šemuél sagte')));
assert(!mk({ terms: ['gott'], fuzzy: true })(R.normalize('gold')));
assert(mk({ terms: ['ארץ'], prefix: true })(R.normalize('ואת הארץ')));
assert(!mk({ terms: ['ארץ'], prefix: false })(R.normalize('ואת הארץ')));
assert(mk({ terms: ['m?er'] })('meer'));
const m = mk({ terms: ['gott', 'erde'], distance: 5 })(t);
assert.strictEqual(S.snippetParts(t, m).filter(p => p.m).map(p => p.t).join(','), 'gott,erde');
assert.strictEqual(S.lev('kitten', 'sitting', 5), 3);
