'use strict';
// Rebuild after changing Field data, attribution parsing, or Westminster anchors.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'../app'),box={window:{}};
const run=file=>vm.runInNewContext(fs.readFileSync(path.join(root,file),'utf8'),box);
run('library-textcrit-hexapla.js');
run('hexapla-morph.js');
run('witness-ren.js');
const GM=require('../app/gmorph'),books=box.window.WITNESS_REN.books,renderings={Aquila:{},Symmachus:{},Theodotion:{}},seen=new Map();
const mcode=(l,m)=>{const ls=l.split('/'),ms=m.slice(1).split('/');let i=ls.findIndex(x=>/\d/.test(x));if(i<0)i=ls.length-1;const suffix=ms.slice(i+1).find(x=>x[0]==='S');return m[0]+(ms[i]||ms.at(-1))+(suffix?'/'+suffix:'');};
const hx=box.window.LibraryHexaplaTC.create({esc:s=>String(s).replace(/[&<>"]/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'})[c])});
const manifest=require('../app/bundled/manifest.json'),rows=[],lemmas={};
for(const book of box.window.LibraryHexaplaTC.BOOKS){
 run('hexapla-data/'+book.replace(/ /g,'_')+'.js');
 const data=box.window.HEXAPLA_DATA[book];
 const item=manifest.items.find(x=>x.title===book&&x.versionTitle?.startsWith('Westminster'));
 if(!item)throw Error('Missing Westminster: '+book);
 const text=JSON.parse(fs.readFileSync(path.join(root,'bundled',item.rel))).text;
 for(const [ref,units] of Object.entries(data.verses)){
  const [c,v]=ref.split(':').map(Number),words=[...(text[c-1]?.[v-1]||'').matchAll(/<span class="w" data-l="([^"]*)"[^>]*>/g)].map(m=>(m[1].split('/').find(x=>/\d/.test(x))||'').trim());
  for(const entry of hx.entries(data,[{ref:book+' '+ref,row:ref}])){
   const unit=units[entry.hexaplaSource.unit];
   if(unit.gap||unit.s==null||unit.s<0)continue;
   const ids=[...new Set(words.slice(unit.s,unit.e+1).filter(Boolean))];
   if(!ids.length)continue;
   for(const row of entry.hexaplaRows){
    const sig=row.siglum.normalize('NFD').replace(/\p{M}/gu,'').toLowerCase();
    const three=/οι γ/.test(sig),sources=[];
    for(const [name,re] of [['Aquila',/(?:^|\s|[,’'])α\./],['Symmachus',/(?:^|\s|,)σ\./],['Theodotion',/(?:^|\s|,)θ\./]])if(three||re.test(sig))sources.push(name);
    if(!sources.length)continue;
    const index=rows.length;
    rows.push({ref:book+' '+ref,unit:entry.hexaplaSource.unit,sources,head:row.attribution,reading:row.reading,forWord:row.forWord,he:unit.h,phrase:unit.e>unit.s,volume:data.vol,page:unit.pg,field:unit.field||ref});
    for(const id of ids)(lemmas[id]||=[]).push(index);
    // Only an exact single MT word anchor is a lexical alignment. Preserve
    // larger fragments in rows for citation, never count them as word matches.
    const surface=row.reading.replace(/\^\d+/g,'').trim().replace(/[.,;·]+$/u,'').trim();
    if(unit.s!==unit.e||row.lxxReference||row.type==='verweis'||/ὁμοίως|ὡς\s|ὡσαύτως|ἀνωτέρω/.test(surface)||!surface||!/^[\p{Script=Greek}\p{M}\s.,;·’'᾿]+$/u.test(surface))continue;
    const tokens=surface.match(/[\p{Script=Greek}\p{M}]+[’'᾿]?/gu)||[];
    if(!tokens.length)continue;
    const tags=[...(text[c-1][v-1]).matchAll(/<span class="w" data-l="([^"]*)" data-m="([^"]*)"[^>]*>/g)];
    if(!tags[unit.s])throw Error('Missing morphology '+book+' '+ref);
    const {type,label,key,surface:headSurface}=require('./field-word-morphology.cjs').group(tokens,box.window.HEXAPLA_MORPH.F,tags[unit.s][2],GM.form);
    const code=mcode(tags[unit.s][1],tags[unit.s][2]),num=books.indexOf(book)*1000000+c*1000+v;
    if(num<0)throw Error('Unknown book '+book);
    for(const source of sources){
     const entry=renderings[source][ids[0]]||=( [[],[]] );
     let g=entry[0].findIndex(l=>l.key===key);
     if(g<0){g=entry[0].length;entry[0].push({key,type,forms:[label]});}
     const occurrence=JSON.stringify([source,book,ref,unit.s,key,headSurface]);
     if(seen.has(occurrence)){seen.get(occurrence)[5].push(index);continue;}
     const cell=[g,code,1,num.toString(36),headSurface,[index]];entry[1].push(cell);seen.set(occurrence,cell);
     const forms=entry[0][g].forms,existing=forms.slice(1).find(f=>f[0]===headSurface);
     if(existing)existing[1]++;else forms.push([headSurface,1]);
    }

   }
  }
 }
}
fs.writeFileSync(path.join(root,'hexapla-word-index.js'),'// Generated by scripts/build-hexapla-word-index.cjs; Field (1875), public domain.\nwindow.HEXAPLA_WORD_INDEX='+JSON.stringify({rows,lemmas,books,renderings})+';\n');
console.log(rows.length+' Field readings indexed for '+Object.keys(lemmas).length+' Hebrew lemmas');
